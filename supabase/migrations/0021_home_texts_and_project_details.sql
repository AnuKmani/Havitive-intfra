create table if not exists public.choose_cards (
  id bigint generated by default as identity primary key,
  title text,
  text text,
  img text,
  img_alt text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.choose_cards enable row level security;
create policy "public read" on public.choose_cards for select to anon, authenticated using (true);
create policy "content insert" on public.choose_cards for insert to authenticated with check ((select public.can_manage_content()));
create policy "content update" on public.choose_cards for update to authenticated
  using ((select public.can_manage_content())) with check ((select public.can_manage_content()));
create policy "content delete" on public.choose_cards for delete to authenticated using ((select public.can_manage_content()));

