-- "What we offer" on the home page becomes fully editable: heading and button text, and the cards (title, text, image).

alter table public.homes add column if not exists heading text;
alter table public.homes add column if not exists button_text text;
update public.homes set heading = 'What we offer', button_text = 'Talk to Experts' where category = 'service' and heading is null;

create table if not exists public.offer_cards (
  id bigint generated by default as identity primary key,
  title text,
  text text,
  img text,
  img_alt text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.offer_cards enable row level security;
create policy "public read" on public.offer_cards for select to anon, authenticated using (true);
create policy "content insert" on public.offer_cards for insert to authenticated with check ((select public.can_manage_content()));
create policy "content update" on public.offer_cards for update to authenticated
  using ((select public.can_manage_content())) with check ((select public.can_manage_content()));
create policy "content delete" on public.offer_cards for delete to authenticated using ((select public.can_manage_content()));

