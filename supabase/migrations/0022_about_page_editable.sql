-- The About page becomes editable from Admin > About page (one row), with its "Why Havitive" cards.

create table if not exists public.about_page (
  id bigint generated by default as identity primary key,
  mission_title text, mission_text text, mission_image text, mission_image_alt text,
  vision_text text, vision_image text, vision_image_alt text,
  companies_kicker text, companies_title text, companies_text text,
  why_title text, why_text text,
  chairman_title text, chairman_text text, chairman_button_text text, chairman_button_link text,
  chairman_name text, chairman_role text, chairman_photo text, chairman_photo_alt text,
  management_kicker text, management_title text, management_text text,
  employees_title text, employees_text text,
  invest_kicker text, invest_title text, invest_text text, invest_image text, invest_image_alt text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.about_strengths (
  id bigint generated by default as identity primary key,
  page_id bigint,
  title text,
  icon text,
  icon_alt text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

alter table public.about_page enable row level security;
create policy "public read" on public.about_page for select to anon, authenticated using (true);
create policy "content insert" on public.about_page for insert to authenticated with check ((select public.can_manage_content()));
create policy "content update" on public.about_page for update to authenticated
  using ((select public.can_manage_content())) with check ((select public.can_manage_content()));
create policy "content delete" on public.about_page for delete to authenticated using ((select public.can_manage_content()));

alter table public.about_strengths enable row level security;
create policy "public read" on public.about_strengths for select to anon, authenticated using (true);
create policy "content insert" on public.about_strengths for insert to authenticated with check ((select public.can_manage_content()));
create policy "content update" on public.about_strengths for update to authenticated
  using ((select public.can_manage_content())) with check ((select public.can_manage_content()));
create policy "content delete" on public.about_strengths for delete to authenticated using ((select public.can_manage_content()));

