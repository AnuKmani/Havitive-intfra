-- HR password help: HR asks from the login page, an admin sets a temporary password, and HR must change it at first sign-in.

alter table public.admins add column if not exists must_change_password boolean not null default false;

create table if not exists public.password_requests (
  id bigint generated by default as identity primary key,
  email text not null,
  status text not null default 'pending' check (status in ('pending', 'done')),
  created_at timestamptz not null default now(),
  handled_at timestamptz,
  handled_by text
);
alter table public.password_requests enable row level security;
-- Only admins can see or remove requests. Nobody writes to the table directly: see the functions below.
create policy "admin read" on public.password_requests for select to authenticated using ((select public.is_admin()));
create policy "admin delete" on public.password_requests for delete to authenticated using ((select public.is_admin()));

-- Called from the login page. Always succeeds quietly, so it can't be used to find out which emails exist.
create or replace function public.request_password_reset(p_email text) returns void
language plpgsql security definer set search_path to '' as $$
declare v_email text := lower(trim(coalesce(p_email, '')));
begin
  if v_email = '' or length(v_email) > 254 then return; end if;
  if (select count(*) from public.password_requests where created_at > now() - interval '1 hour') >= 20 then return; end if;
  if not exists (
    select 1 from public.admins a join auth.users u on u.id = a.user_id
    where a.role = 'hr' and lower(u.email) = v_email
  ) then return; end if;
  if exists (select 1 from public.password_requests where email = v_email and status = 'pending') then return; end if;
  insert into public.password_requests (email) values (v_email);
end $$;

-- Admin gives an HR user a temporary password. HR is signed out everywhere and must choose a new password at the next sign-in.
create or replace function public.admin_set_temp_password(p_request_id bigint, p_password text) returns void
language plpgsql security definer set search_path to '' as $$
declare v_email text; v_uid uuid;
begin
  if not (select public.is_admin()) then raise exception 'Not allowed'; end if;
  if p_password is null or length(p_password) < 10 or length(p_password) > 72 then
    raise exception 'Use a password of 10 to 72 characters.';
  end if;
  select email into v_email from public.password_requests where id = p_request_id and status = 'pending';
  if v_email is null then raise exception 'That request is no longer waiting.'; end if;
  select u.id into v_uid from auth.users u join public.admins a on a.user_id = u.id
    where lower(u.email) = v_email and a.role = 'hr';
  if v_uid is null then raise exception 'No HR account with that email.'; end if;

  update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')), updated_at = now() where id = v_uid;
  update public.admins set must_change_password = true where user_id = v_uid;
  delete from auth.sessions where user_id = v_uid;
  update public.password_requests set status = 'done', handled_at = now(),
    handled_by = (select email from auth.users where id = (select auth.uid())) where id = p_request_id;
end $$;

-- Called by the signed-in user after choosing a new password.
create or replace function public.clear_must_change_password() returns void
language sql security definer set search_path to '' as $$
  update public.admins set must_change_password = false where user_id = (select auth.uid());
$$;

revoke all on function public.request_password_reset(text) from public;
grant execute on function public.request_password_reset(text) to anon, authenticated;
revoke all on function public.admin_set_temp_password(bigint, text), public.clear_must_change_password() from public, anon;
grant execute on function public.admin_set_temp_password(bigint, text), public.clear_must_change_password() to authenticated;
