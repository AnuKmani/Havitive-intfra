-- Showcase menu: CSR activities, handing over events, awards, media, project videos and video testimonials.
-- One table; "section" tells which page an item belongs to. Edited in Admin > Showcase.

create table if not exists public.showcase_items (
  id bigint generated by default as identity primary key,
  section text not null check (section in ('csr', 'handover', 'awards', 'media', 'project-videos', 'testimonial-videos')),
  title text not null,
  description text,
  image text,
  image_alt text,
  video_url text,
  link_url text,
  event_date text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
create index if not exists showcase_items_section_idx on public.showcase_items (section, created_at desc);

alter table public.showcase_items enable row level security;
create policy "public read" on public.showcase_items for select to anon, authenticated using (true);
create policy "content insert" on public.showcase_items for insert to authenticated with check ((select public.can_manage_content()));
create policy "content update" on public.showcase_items for update to authenticated
  using ((select public.can_manage_content())) with check ((select public.can_manage_content()));
create policy "content delete" on public.showcase_items for delete to authenticated using ((select public.can_manage_content()));
